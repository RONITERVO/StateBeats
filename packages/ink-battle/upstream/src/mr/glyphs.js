export function glyph(
  b,
  name,
  x = 0,
  y = 0.05,
  z = 0.033,
  size = 0.022,
  color = "#342d2b",
) {
  for (const path of GLYPHS[name] || [])
    b.path(
      path.map(([xx, yy]) => [x + xx * size, y + yy * size, z]),
      0.0035,
      color,
    );
}
